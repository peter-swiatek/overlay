/**
 * The flag code for an iRacing FlairName; null for "-none-", "Global", empty or unknown names.
 * Matching ignores case, spaces and punctuation ("Virgin Islands (U.S.)" = "virginislandsus").
 */
export function nationalityCode(flairName: string | null): string | null {
  if (flairName === null) return null;
  const key = flairName.toLowerCase().replace(/[^a-z0-9]/g, "");
  return BY_NAME[key] ?? null;
}
